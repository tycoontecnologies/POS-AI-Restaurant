              SizedBox(height: AppSpacing.xs),
              ShimmerEffect(width: 80, height: 16),
              SizedBox(height: AppSpacing.xs),
              ShimmerEffect(width: 100, height: 16),
              SizedBox(height: AppSpacing.sm),
